import { test } from 'node:test';
import assert from 'node:assert/strict';
import { call, load, memoryBackend } from '../helpers/convex-memory.ts';
const consumer = load('intakeConsumer');
const intake = load('intake');
const owner = 'intake-owner';
const hash = 'd'.repeat(64);
async function setup() {
  process.env.RUNNER_KEY = owner;
  delete process.env.RUNNER_KEY_NEXT;
  const b = memoryBackend();
  await call(b.ctx, intake.provision, { clientId: 'nanobot', keyHash: hash });
  const message = { messageId: 'email:robby:INBOX:42:1', source: 'email', sourceMessageId: '42:1', text: 'Subject: New task\n\nOriginal body', sentAt: '2026-11-08T09:00:00Z' };
  const made = await call(b.ctx, intake.accept, { keyHash: hash, message });
  return { ...b, message, receipt: made.receipt, args: { key: owner, runnerId: 'mac' } };
}
test('only the bound runner consumes; leases fence competing claims and saved receipts stay immutable', async () => {
  const b = await setup();
  assert.deepEqual(await call(b.ctx, consumer.pendingIntake, b.args), []);
  await call(b.ctx, consumer.bindConsumer, { clientId: 'nanobot', runnerId: 'mac' });
  assert.equal((await call(b.ctx, consumer.pendingIntake, { ...b.args, runnerId: 'other' })).length, 0);
  const [item] = await call(b.ctx, consumer.pendingIntake, b.args);
  assert.equal(item.receiptId, b.receipt.receiptId);
  assert.deepEqual(item.message, b.message);
  const claim = { ...b.args, receiptId: item.receiptId, leaseToken: 'a'.repeat(32) };
  const taken = await call(b.ctx, consumer.claimIntake, claim);
  assert.equal(taken.state, 'claimed');
  assert.match(taken.threadId, /^[a-f0-9-]{36}$/);
  assert.equal((await call(b.ctx, consumer.claimIntake, { ...claim, leaseToken: 'b'.repeat(32) })).state, 'busy');
  assert.equal(await call(b.ctx, consumer.finishIntake, { ...claim, leaseToken: 'b'.repeat(32) }), false);
  assert.equal(await call(b.ctx, consumer.finishIntake, claim), true);
  assert.equal(await call(b.ctx, consumer.finishIntake, claim), true, 'lost success response is safe');
  assert.deepEqual(await call(b.ctx, consumer.pendingIntake, b.args), []);
  assert.equal(b.rows('intakeMessages')[0].deliveryState, 'saved');
  assert.equal(b.rows('intakeMessages')[0].deliveryThreadId, taken.threadId);
  assert.deepEqual((await call(b.ctx, intake.receipt, { keyHash: hash, messageId: b.message.messageId })).receipt, b.receipt);
});
test('expired claims recover with the same draft ID; stale owners, revoked and ignored clients cannot consume', async () => {
  const b = await setup();
  await call(b.ctx, consumer.bindConsumer, { clientId: 'nanobot', runnerId: 'mac' });
  const claim = { ...b.args, receiptId: b.receipt.receiptId, leaseToken: 'a'.repeat(32) };
  const first = await call(b.ctx, consumer.claimIntake, claim);
  await b.ctx.db.patch(b.receipt.receiptId, { leaseUntil: 0 });
  const next = await call(b.ctx, consumer.claimIntake, { ...claim, leaseToken: 'b'.repeat(32) });
  assert.equal(first.threadId, next.threadId);
  assert.equal(await call(b.ctx, consumer.finishIntake, claim), false);
  await assert.rejects(call(b.ctx, consumer.bindConsumer, { clientId: 'nanobot', runnerId: 'other' }), /bound/);
  await call(b.ctx, intake.revoke, { clientId: 'nanobot' });
  assert.deepEqual(await call(b.ctx, consumer.pendingIntake, b.args), []);
  assert.equal((await call(b.ctx, consumer.claimIntake, claim)).state, 'unavailable');
  await call(b.ctx, intake.provision, { clientId: 'nanobot', keyHash: hash });
  await assert.rejects(call(b.ctx, consumer.ignoreMessage, { clientId: 'nanobot', messageId: b.message.messageId }), /lease/);
  await b.ctx.db.patch(b.receipt.receiptId, { leaseUntil: 0 });
  await call(b.ctx, consumer.ignoreMessage, { clientId: 'nanobot', messageId: b.message.messageId });
  assert.deepEqual(await call(b.ctx, consumer.pendingIntake, b.args), []);
  assert.equal((await call(b.ctx, consumer.claimIntake, claim)).state, 'unavailable');
  assert.deepEqual((await call(b.ctx, intake.receipt, { keyHash: hash, messageId: b.message.messageId })).receipt, b.receipt);
  await assert.rejects(call(b.ctx, consumer.pendingIntake, { ...b.args, key: 'tbi_not-a-runner-key' }));
  const otherKey = 'other-runner-key';
  await b.ctx.db.insert('runnerKeys', { runnerId: 'other', keyHash: await load('lib').sha256(otherKey), name: 'other', createdAt: Date.now() });
  await assert.rejects(call(b.ctx, consumer.pendingIntake, { key: otherKey, runnerId: 'mac' }), /can't/);
  assert.deepEqual(await call(b.ctx, consumer.pendingIntake, { key: otherKey, runnerId: 'other' }), []);
  assert.equal((await call(b.ctx, consumer.claimIntake, { key: otherKey, runnerId: 'other', receiptId: b.receipt.receiptId, leaseToken: 'c'.repeat(32) })).state, 'unavailable');
});
